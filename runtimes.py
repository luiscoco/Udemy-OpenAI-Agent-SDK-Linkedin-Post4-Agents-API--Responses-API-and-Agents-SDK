"""Three live runtime boundaries plus a deliberately deterministic offline simulation."""
import asyncio
import json
import os
from pathlib import Path
from uuid import uuid4

from core import INSTRUCTIONS, initial_input, sales_facts, save_json


def offline(runtime, question, state, data_path):
    """Teaching simulation: no SDK, model, remote session, or API calls."""
    facts = state.setdefault("demo_facts", sales_facts(data_path))
    number = len(state["turns"]) + 1
    state.setdefault("simulated_handle", f"demo_{runtime}_{uuid4().hex[:12]}")
    answer = (
        f"OFFLINE SIMULATION | {runtime} | turn {number}\n"
        f"{facts['company']} - {facts['period']}\n"
        f"Revenue: {facts['currency']} {facts['revenue']}\n"
        f"Cost: {facts['currency']} {facts['cost']}\n"
        f"Gross profit: {facts['currency']} {facts['gross_profit']}\n"
        f"Gross margin: {facts['gross_margin_percent'] or 'undefined (zero revenue)'}"
        f"{'%' if facts['gross_margin_percent'] is not None else ''}\n"
        "Margin uses revenue as the denominator; markup uses cost.\n"
        "This fixed teaching response is not generated by a model. "
        "It does not interpret arbitrary questions."
    )
    return answer, ["simulate: load facts", f"simulate: {runtime} runtime", "simulate: save local state"]


def openai_client():
    if not os.environ.get("OPENAI_API_KEY"):
        raise ValueError("Live mode needs OPENAI_API_KEY. Offline mode needs no key.")
    try:
        from openai import OpenAI
    except ImportError as exc:
        raise ValueError("Install live dependencies: python -m pip install -r requirements.txt") from exc
    return OpenAI(timeout=120, max_retries=0)


def direct_response(client, model, question, state, facts):
    params = dict(model=model, instructions=INSTRUCTIONS, store=True)
    previous = state.get("previous_response_id")
    params["input"] = question if previous else initial_input(question, facts)
    if previous:
        params["previous_response_id"] = previous
    # The application decides when to make the next request. There is no SDK runner here.
    result = client.responses.create(**params)
    if getattr(result, "status", None) != "completed" or not result.output_text:
        raise RuntimeError("Response did not complete with text; inspect the response before continuing.")
    state["previous_response_id"] = result.id
    return result.output_text, [f"responses.create(previous_response_id={previous!r})", f"saved response id: {result.id}"]


async def sdk_turn(model, question, state, facts_path, state_file):
    try:
        from agents import Agent, Runner, SQLiteSession, function_tool, set_tracing_disabled
    except ImportError as exc:
        raise ValueError("Install live dependencies: python -m pip install -r requirements.txt") from exc
    set_tracing_disabled(True)
    events = []

    @function_tool
    def get_sales_facts() -> str:
        """Return verified sales totals and gross margin for the fictional company."""
        events.append("local function tool: get_sales_facts")
        return json.dumps(sales_facts(facts_path))

    agent = Agent(name="Sales report tutor", model=model,
                  instructions=INSTRUCTIONS + " Call get_sales_facts to obtain the sales figures.",
                  tools=[get_sales_facts])
    storage_key = state.setdefault("sdk_storage_key", "classroom_" + uuid4().hex)
    database = Path(state_file).parent / "sdk_history.sqlite"
    state["sdk_database"] = str(database.resolve())
    # Persist the key before Runner writes history, so it survives a later interruption.
    save_json(Path(state_file), state)
    session = SQLiteSession(storage_key, str(database))
    try:
        result = await Runner.run(agent, question, session=session, max_turns=6)
        output = str(result.final_output)
    finally:
        session.close()
    return output, ["Runner.run in application process", *events, f"SQLite storage key: {storage_key}"]


def consume_managed(events, log):
    """Idle and a disconnected stream do not establish successful completion."""
    for event in events:
        log.append(event.type)
        if event.type == "error" or event.type in {"agent.session.failed", "agent.session.environment.failed"}:
            raise RuntimeError(f"Managed session failed: {event.type}")
        turn = getattr(event, "turn", None)
        is_root = turn is not None and getattr(turn, "subagent_id", None) is None
        if is_root and event.type in {"agent.session.turn.failed", "agent.session.turn.cancelled"}:
            raise RuntimeError(f"Managed turn did not complete: {event.type}")
        if is_root and event.type == "agent.session.turn.completed":
            return
    raise RuntimeError("Managed stream ended before a completed root turn. Inspect saved session items.")


def managed_turn(client, model, question, state, facts, state_file):
    try:
        sessions = client.beta.agents.sessions
    except AttributeError as exc:
        raise ValueError("Your openai package lacks beta.agents. Upgrade it and check Agents API access.") from exc
    log = []
    session_id = state.get("managed_session_id")
    if not session_id:
        # Create with initial input; no container, filesystem, or local Python tool is exposed.
        with sessions.create(agent={"model": model, "instructions": INSTRUCTIONS},
                             environment={"type": "none"},
                             input=initial_input(question, facts), stream=True).with_result_collection() as stream:
            def remember_session():
                for event in stream:
                    # Save the real session id as soon as the server provides it.
                    remote = getattr(event, "session", None)
                    if remote is not None and getattr(remote, "id", None):
                        state["managed_session_id"] = remote.id
                        save_json(Path(state_file), state)
                    yield event
            consume_managed(remember_session(), log)
            result = stream.get_final_result()
        state["managed_session_id"] = result.session_id
        save_json(Path(state_file), state)
        return result.output_text, log

    # A pending message is never silently resubmitted or replaced after an uncertain failure.
    if state.get("pending_submission"):
        raise ValueError("An earlier managed submission needs inspection. See README recovery instructions.")
    submission = {"idempotency_key": str(uuid4()), "text": question}
    with sessions.events.stream(session_id) as stream:
        state["pending_submission"] = submission
        save_json(Path(state_file), state)
        sessions.events.create(session_id, idempotency_key=submission["idempotency_key"], events=[{
            "type": "agent.session.input.message",
            "input": [{"role": "user", "content": [{"type": "input_text", "text": question}]}],
        }])
        consume_managed(stream, log)
    # Saved items are the durable transcript. Keep their original JSON as an artifact.
    items = [item.model_dump(mode="json") for item in sessions.items.list(session_id, order="asc", limit=100)]
    state["managed_items"] = items
    state.pop("pending_submission", None)
    messages = []
    for item in items:
        if item.get("role") == "assistant":
            for part in item.get("content", []):
                if isinstance(part.get("text"), str):
                    messages.append(part["text"])
    if not messages:
        raise RuntimeError("Turn completed but no assistant text found. Inspect managed_items in state JSON.")
    return messages[-1], log


def live(runtime, model, question, state, data_path, state_file):
    # SDK and Responses can also support other state strategies. This lab chooses one each.
    client = openai_client()
    try:
        if runtime == "responses":
            return direct_response(client, model, question, state, sales_facts(data_path))
        if runtime == "sdk":
            return asyncio.run(sdk_turn(model, question, state, data_path, state_file))
        return managed_turn(client, model, question, state, sales_facts(data_path), state_file)
    finally:
        client.close()
